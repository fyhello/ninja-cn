export function toTraditional(simplifiedText) {
  if (!simplifiedText || typeof simplifiedText !== 'string') return simplifiedText;

  // 1. 优先匹配专有名词全词
  if (POE2_TW_SPECIAL_TERMS[simplifiedText]) {
    return POE2_TW_SPECIAL_TERMS[simplifiedText];
  }

  // 2. 逐词替换专有名词
  let text = simplifiedText;
  for (const [s, t] of Object.entries(POE2_TW_SPECIAL_TERMS)) {
    if (text.includes(s)) {
      text = text.replaceAll(s, t);
    }
  }

  // 3. 逐字标准简繁转换
  let out = '';
  for (const ch of text) {
    out += S2T_CHAR_MAP[ch] || ch;
  }
  return out;
}
